export function isSolidTile(col: number, row: number): boolean {
  if (row < 0 || row >= LEVEL_ROWS || col < 0 || col >= LEVEL_COLS) return row >= LEVEL_ROWS;
  return LEVEL_DATA[row][col] === 1;
}

export function drawTiles(ctx: CanvasRenderingContext2D, cameraX: number) {
  const startCol = Math.max(0, Math.floor(cameraX / TILE_SIZE));
  const endCol = Math.min(LEVEL_COLS - 1, startCol + Math.ceil(ctx.canvas.width / TILE_SIZE) + 1);

  for (let row = 0; row < LEVEL_ROWS; row++) {
    for (let col = startCol; col <= endCol; col++) {
      if (LEVEL_DATA[row][col] === 1) {
        const sx = col * TILE_SIZE - cameraX;
        const sy = row * TILE_SIZE;
        const isTop = row === 0 || LEVEL_DATA[row - 1]?.[col] !== 1;

        // Base metal fill
        const grad = ctx.createLinearGradient(sx, sy, sx, sy + TILE_SIZE);
        if (isTop) {
          grad.addColorStop(0, '#3af');
          grad.addColorStop(0.08, '#1a2a3a');
          grad.addColorStop(1, '#0d1520');
        } else {
          grad.addColorStop(0, '#1a2a3a');
          grad.addColorStop(1, '#0d1520');
        }
        ctx.fillStyle = grad;
        ctx.fillRect(sx, sy, TILE_SIZE, TILE_SIZE);

        // Top edge glow
        if (isTop) {
          ctx.shadowColor = '#00cfff';
          ctx.shadowBlur = 8;
          ctx.fillStyle = '#00cfff';
          ctx.fillRect(sx, sy, TILE_SIZE, 2);
          ctx.shadowBlur = 0;
        }

        // Subtle grid line
        ctx.strokeStyle = 'rgba(0,180,255,0.1)';
        ctx.lineWidth = 0.5;
        ctx.strokeRect(sx, sy, TILE_SIZE, TILE_SIZE);

        // Rivets on top tiles
        if (isTop && col % 4 === 0) {
          ctx.fillStyle = '#4af';
          ctx.beginPath();
          ctx.arc(sx + 6, sy + 6, 2, 0, Math.PI * 2);
          ctx.fill();
          ctx.beginPath();
          ctx.arc(sx + TILE_SIZE - 6, sy + 6, 2, 0, Math.PI * 2);
          ctx.fill();
        }
      }
    }
  }
}

